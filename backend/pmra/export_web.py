"""Export the index, benchmark results, extractions and registry for the Netlify site."""
from __future__ import annotations

import json
from dataclasses import asdict

from . import config
from .extraction import extract
from .ingest import load_chunks
from .llm import LLM
from .registry import Registry


def export():
    config.WEB_DATA.mkdir(parents=True, exist_ok=True)
    chunks = load_chunks()
    (config.WEB_DATA / "index.json").write_text(json.dumps([asdict(c) for c in chunks]))
    llm = LLM()
    docs = sorted({c.doc_id for c in chunks})
    exts = [extract([c for c in chunks if c.doc_id == d], llm)[0].model_dump() | {"model_version": "offline-rules-v1" if llm.offline else llm.version_id}
            for d in docs]
    (config.WEB_DATA / "extractions.json").write_text(json.dumps(exts, indent=1))
    benches = {}
    for p in sorted(config.ARTIFACTS.glob("bench_*.json")):
        b = json.loads(p.read_text())
        benches[p.stem.removeprefix("bench_")] = b
    (config.WEB_DATA / "benchmarks.json").write_text(json.dumps(benches, indent=1))
    reg = Registry().export()
    qp = config.ARTIFACTS / "qlora_comparison.json"
    reg["qlora_comparison"] = json.loads(qp.read_text()) if qp.exists() else None
    (config.WEB_DATA / "registry.json").write_text(json.dumps(reg, indent=1))
    # copy the copy-ready server index for Netlify functions
    fn_data = config.ROOT / "netlify" / "functions" / "lib" / "index-data.mjs"
    fn_data.write_text("// generated by pmra.export_web\nexport default " + json.dumps([asdict(c) for c in chunks]) + ";\n")
    print(f"Exported {len(chunks)} chunks, {len(exts)} extractions, {len(benches)} benchmark sets to {config.WEB_DATA}")


if __name__ == "__main__":
    export()
